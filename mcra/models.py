"""
Domain entities and data models for the MCRA discrete-event 5G network slicing simulator.
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import Optional, List, Dict, Any


class SliceType(str, Enum):
    EMBB = "eMBB"
    URLLC = "URLLC"
    MMTC = "mMTC"


class TopologyMode(str, Enum):
    EDGE_ONLY = "edge_only"
    CLOUD_ONLY = "cloud_only"
    PARALLEL_HYBRID = "parallel_hybrid"


class RequestStatus(str, Enum):
    PENDING = "PENDING"
    ADMITTED = "ADMITTED"
    BLOCKED_CAPACITY = "BLOCKED_CAPACITY"
    BLOCKED_QOS_UNSATISFIABLE = "BLOCKED_QOS_UNSATISFIABLE"
    BLOCKED_NO_ROUTE = "BLOCKED_NO_ROUTE"
    BLOCKED_SEARCH_LIMIT = "BLOCKED_SEARCH_LIMIT"
    BLOCKED_INVALID_REQUEST = "BLOCKED_INVALID_REQUEST"
    DROPPED_QUEUE_OVERFLOW = "DROPPED_QUEUE_OVERFLOW"
    DROPPED_TIMEOUT = "DROPPED_TIMEOUT"
    COMPLETED = "COMPLETED"


class EventType(str, Enum):
    REQUEST_ARRIVAL = "REQUEST_ARRIVAL"
    REQUEST_ADMITTED = "REQUEST_ADMITTED"
    REQUEST_BLOCKED = "REQUEST_BLOCKED"
    PACKET_ENQUEUED = "PACKET_ENQUEUED"
    LINK_SERVICE_STARTED = "LINK_SERVICE_STARTED"
    LINK_SERVICE_COMPLETED = "LINK_SERVICE_COMPLETED"
    COMPUTE_SERVICE_STARTED = "COMPUTE_SERVICE_STARTED"
    COMPUTE_SERVICE_COMPLETED = "COMPUTE_SERVICE_COMPLETED"
    PACKET_DELIVERED = "PACKET_DELIVERED"
    RESOURCE_RELEASED = "RESOURCE_RELEASED"
    QUEUE_OVERFLOW_DROP = "QUEUE_OVERFLOW_DROP"
    DEADLINE_EXPIRED = "DEADLINE_EXPIRED"


class ResourceType(str, Enum):
    COMMUNICATION = "communication"
    COMPUTATION = "computation"


class NodeTier(str, Enum):
    UE = "ue"
    EDGE_ROUTER = "edge_router"
    EDGE = "edge"
    CLOUD = "cloud"
    DESTINATION = "destination"


@dataclass(frozen=True)
class QoSProfile:
    """QoS SLA requirements for a network slice."""
    slice_type: SliceType
    deadline_ms: float
    max_loss_pct: float
    min_bw_mbps: float
    min_compute_units: float


@dataclass
class CommunicationLink:
    """Communication link connecting two network entities."""
    link_id: str
    src_node: str
    dst_node: str
    capacity_mbps: float
    propagation_delay_ms: float
    queue_capacity_packets: int = 200

    def to_dict(self) -> Dict[str, Any]:
        return {
            "link_id": self.link_id,
            "src_node": self.src_node,
            "dst_node": self.dst_node,
            "capacity_mbps": self.capacity_mbps,
            "propagation_delay_ms": self.propagation_delay_ms,
            "queue_capacity_packets": self.queue_capacity_packets,
        }


@dataclass
class ComputeNode:
    """Compute processing node (Edge MEC or Centralized Cloud)."""
    node_id: str
    tier: NodeTier
    capacity_units: float
    base_delay_ms: float = 0.0
    queue_capacity_tasks: int = 200

    def to_dict(self) -> Dict[str, Any]:
        return {
            "node_id": self.node_id,
            "tier": self.tier.value,
            "capacity_units": self.capacity_units,
            "base_delay_ms": self.base_delay_ms,
            "queue_capacity_tasks": self.queue_capacity_tasks,
        }


@dataclass
class Route:
    """Ordered path consisting of links and target compute node."""
    route_id: str
    path_name: str
    links: List[CommunicationLink]
    compute_node: ComputeNode

    def to_dict(self) -> Dict[str, Any]:
        return {
            "route_id": self.route_id,
            "path_name": self.path_name,
            "links": [l.link_id for l in self.links],
            "compute_node": self.compute_node.node_id,
        }


@dataclass
class Packet:
    """Individual data transmission unit for visual packet journey and queuing."""
    packet_id: str
    parent_request_id: str
    sequence_number: int
    total_packets: int
    payload_bits: float
    creation_time_ms: float
    current_hop: int = 0
    delivered: bool = False
    delivery_time_ms: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "packet_id": self.packet_id,
            "parent_request_id": self.parent_request_id,
            "sequence_number": self.sequence_number,
            "total_packets": self.total_packets,
            "payload_bits": self.payload_bits,
            "creation_time_ms": self.creation_time_ms,
            "current_hop": self.current_hop,
            "delivered": self.delivered,
            "delivery_time_ms": self.delivery_time_ms,
        }


@dataclass
class ServiceRequest:
    """Service request generated by a UE belonging to a tenant and slice."""
    request_id: str
    tenant_id: str
    ue_id: str
    slice_type: SliceType
    arrival_time_ms: float
    payload_bits: float
    compute_demand: float
    deadline_ms: float
    route_candidate: Optional[str] = None
    status: RequestStatus = RequestStatus.PENDING
    status_reason: str = ""
    predicted_delay_ms: float = 0.0
    actual_e2e_delay_ms: float = 0.0
    completion_time_ms: float = 0.0
    allocated_resources: Dict[str, float] = field(default_factory=dict)
    reservation_id: Optional[str] = None
    packets: List[Packet] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "request_id": self.request_id,
            "tenant_id": self.tenant_id,
            "ue_id": self.ue_id,
            "slice_type": self.slice_type.value,
            "arrival_time_ms": round(self.arrival_time_ms, 2),
            "payload_bits": round(self.payload_bits, 1),
            "compute_demand": round(self.compute_demand, 2),
            "deadline_ms": round(self.deadline_ms, 2),
            "route_candidate": self.route_candidate,
            "status": self.status.value,
            "status_reason": self.status_reason,
            "predicted_delay_ms": round(self.predicted_delay_ms, 2),
            "actual_e2e_delay_ms": round(self.actual_e2e_delay_ms, 2),
            "completion_time_ms": round(self.completion_time_ms, 2),
            "allocated_resources": {k: round(v, 3) for k, v in self.allocated_resources.items()},
            "reservation_id": self.reservation_id,
            "packet_count": len(self.packets),
        }


@dataclass
class SimulationEvent:
    """Immutable discrete event in the simulation scheduler."""
    time_ms: float
    sequence: int
    event_type: EventType
    request_id: str
    packet_id: Optional[str] = None
    node_or_link_id: Optional[str] = None
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "time_ms": round(self.time_ms, 3),
            "sequence": self.sequence,
            "event_type": self.event_type.value,
            "request_id": self.request_id,
            "packet_id": self.packet_id,
            "node_or_link_id": self.node_or_link_id,
            "metadata": self.metadata,
        }


@dataclass
class AllocationStepTrace:
    """Detailed audit trace of one iteration in the MCRA optimization loop."""
    iteration: int
    selected_resource: str
    resource_type: str
    increment: float
    marginal_cost: float
    candidates_evaluated: List[Dict[str, Any]]
    predicted_delay_before: float
    predicted_delay_after: float
    remaining_capacity_after: float

    def to_dict(self) -> Dict[str, Any]:
        return {
            "iteration": self.iteration,
            "selected_resource": self.selected_resource,
            "resource_type": self.resource_type,
            "increment": round(self.increment, 4),
            "marginal_cost": round(self.marginal_cost, 6),
            "candidates_evaluated": self.candidates_evaluated,
            "predicted_delay_before": round(self.predicted_delay_before, 3),
            "predicted_delay_after": round(self.predicted_delay_after, 3),
            "remaining_capacity_after": round(self.remaining_capacity_after, 3),
        }


@dataclass
class MCRADecisionTrace:
    """Complete decision trace for a request admission attempt."""
    request_id: str
    tenant_id: str
    slice_type: str
    route_name: str
    deadline_ms: float
    admitted: bool
    status_reason: str
    final_predicted_delay_ms: float
    iterations: List[AllocationStepTrace] = field(default_factory=list)
    initial_allocations: Dict[str, float] = field(default_factory=dict)
    final_allocations: Dict[str, float] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "request_id": self.request_id,
            "tenant_id": self.tenant_id,
            "slice_type": self.slice_type,
            "route_name": self.route_name,
            "deadline_ms": round(self.deadline_ms, 2),
            "admitted": self.admitted,
            "status_reason": self.status_reason,
            "final_predicted_delay_ms": round(self.final_predicted_delay_ms, 2),
            "iterations_count": len(self.iterations),
            "iterations": [it.to_dict() for it in self.iterations],
            "initial_allocations": {k: round(v, 3) for k, v in self.initial_allocations.items()},
            "final_allocations": {k: round(v, 3) for k, v in self.final_allocations.items()},
        }
